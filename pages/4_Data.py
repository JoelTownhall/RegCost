@st.cache_data(ttl=3600)
def load_csv(filename: str) -> pd.DataFrame:
    """Load a CSV from output/; return empty DataFrame if file is missing."""
    path = DATA_DIR / filename
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


