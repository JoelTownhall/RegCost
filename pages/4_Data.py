# ── Helper: get weighted average of a rate column for a given year ────────────
def wavg(df, val_col, wt_col, year):
    sub = df[df["year"] == year].dropna(subset=[val_col, wt_col])
    if sub.empty or sub[wt_col].sum() == 0:
        return None
    return (sub[val_col] * sub[wt_col]).sum() / sub[wt_col].sum()


def simple_avg(df, val_col, year):
    sub = df[df["year"] == year][val_col].dropna()
    return sub.mean() if not sub.empty else None


