def _delta_str(val, prev):
    """Format a numeric delta with sign, or None if unavailable."""
    if val is None or prev is None or prev == 0:
        return None
    return round(val - prev, 1)


def _pct_delta(val, prev):
    if val is None or prev is None or prev == 0:
        return None
    return f"{val - prev:+.1f} pp"   # percentage-point change


def _count_delta(val, prev):
    if val is None or prev is None:
        return None
    d = int(val - prev)
    return f"{d:+,}"


def _interp(metric: str, value, delta) -> tuple[str, str]:
    """
    Return (short interpretation, colour hint: 'normal'|'good'|'warn'|'neutral').
    delta is the year-on-year change (positive = went up).
    """
    if value is None:
        return "No data", "neutral"

    if metric == "entry_rate":
        level_txt = "High" if value > 15 else "Moderate" if value > 8 else "Low"
        if delta is None:
            return f"{level_txt} rate of new entrants", "neutral"
        dir_txt = "rising ↑" if delta > 0.5 else "falling ↓" if delta < -0.5 else "stable →"
        if value < 8 and delta < 0:
            return f"Low & falling — investigate barriers to entry", "warn"
        if value > 15:
            return f"High — market is highly contestable", "good"
        return f"{level_txt} new-entrant activity, {dir_txt}", "neutral"

    if metric == "exit_rate":
        if delta is None:
            return "Measures firms ceasing trading", "neutral"
        dir_txt = "rising ↑" if delta > 0.5 else "falling ↓" if delta < -0.5 else "stable →"
        return f"Exit rate {dir_txt}", "neutral"

    if metric == "net_entry":
        if value > 2:
            return "Growing — more entrants than exits", "good"
        if value < -2:
            return "Contracting — exits exceeding entries", "warn"
        return "Roughly balanced entry and exit", "neutral"

    if metric == "total_firms":
        if delta is None:
            return "Total actively trading businesses", "neutral"
        dir_txt = "grew" if delta > 0 else "shrank"
        return f"Firm count {dir_txt} year-on-year", "good" if delta > 0 else "warn"

    if metric == "labour_share":
        level_txt = "High (labour-intensive)" if value > 60 else \
                    "Low (capital-intensive)" if value < 30 else "Moderate"
        if delta is None:
            return f"{level_txt}", "neutral"
        if delta < -2:
            return f"Declining ↓ — profits capturing more value; possible market power signal", "warn"
        if delta > 2:
            return f"Rising ↑ — labour capturing more of value added", "good"
        return f"{level_txt}, broadly stable", "neutral"

    if metric == "survival_4yr":
        if value > 75:
            return "Most businesses survive 4 years — stable industry", "neutral"
        if value > 60:
            return "Moderate survival — typical of competitive markets", "neutral"
        return "Lower survival — competitive pressure or difficult conditions", "warn"

    if metric == "non_emp_share":
        if value > 70:
            return "Dominated by sole traders / non-employing businesses", "neutral"
        if delta is not None and delta > 3:
            return "Non-employing share rising — possible fragmentation", "neutral"
        return "Mix of employing and non-employing businesses", "neutral"

    return "", "neutral"


def _metric_card(label: str, value_str: str, delta_str, interp: str, colour: str):
    """Render a metric with delta and interpretation caption."""
    delta_kwargs = {"delta": delta_str} if delta_str else {}
    st.metric(label=label, value=value_str, **delta_kwargs)
    icon = "✅" if colour == "good" else "⚠️" if colour == "warn" else "ℹ️"
    if interp:
        st.caption(f"{icon} {interp}")


