    size_cols = ["non_employing","emp_1_4","emp_5_19","emp_20_199","emp_200plus"]
    size_labels_map = {"non_employing":"Non-employing","emp_1_4":"1–4 emp",
                       "emp_5_19":"5–19 emp","emp_20_199":"20–199 emp","emp_200plus":"200+ emp"}
    if not ed.empty:
        col_a, col_b = st.columns(2)
        yr_opts = sorted(ed["year"].unique(), reverse=True)
        with col_a:
            sel_yr = st.radio("Year", yr_opts, horizontal=True, key="size_yr2")
            totals = ed[ed["year"]==sel_yr][size_cols].sum()
            df_sz = pd.DataFrame({"Band":[size_labels_map[c] for c in size_cols],
                                  "Count":[int(totals[c]) for c in size_cols]})
            fig = px.pie(df_sz, names="Band", values="Count",
                         color_discrete_sequence=px.colors.sequential.Blues[::-1][1:], hole=0.38)
            fig.update_traces(textposition="inside", textinfo="percent+label")
            fig.update_layout(showlegend=False, height=340, title=f"Size mix — June {int(sel_yr)}")
            st.plotly_chart(fig, use_container_width=True)
        with col_b:
            # Stacked bar comparing both years
            df_all = ed.groupby("year")[size_cols].sum().reset_index()
            df_melt = df_all.melt(id_vars="year", value_vars=size_cols,
                                  var_name="band", value_name="count")
            df_melt["label"] = df_melt["band"].map(size_labels_map)
            fig2 = px.bar(df_melt, x="year", y="count", color="label",
                          barmode="stack",
                          labels={"count":"Businesses","year":"Year","label":"Size band"},
                          title="Size structure over time",
                          color_discrete_sequence=px.colors.sequential.Blues[1:])
            fig2.update_layout(yaxis_tickformat=",", height=340, legend_title="")
            st.plotly_chart(fig2, use_container_width=True)
        st.caption("ABS 8165.0 DC02 — class level")
    else:
        st.info("No firm size data for this selection.")

