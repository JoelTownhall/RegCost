@st.cache_data(ttl=3600)
def load_all() -> dict:
    def read(f):
        p = DATA_DIR / f
        return pd.read_csv(p) if p.exists() else pd.DataFrame()

    dc = read("abs_division_counts.csv")
    ds = read("abs_division_survival.csv")
    bc = read("abs_business_counts.csv")
    ed = read("abs_employment_dist.csv")
    ws = read("abs_wage_share.csv")

    subdiv_to_div: dict = {}
    if not ws.empty:
        for _, r in ws[["subdivision_code","division"]].drop_duplicates().iterrows():
            subdiv_to_div[r["subdivision_code"]] = r["division"]

    for df in [bc, ed]:
        if not df.empty:
            df["subdivision_code"] = df["anzsic_group_code"].str[:2]
            df["division"] = df["subdivision_code"].map(subdiv_to_div)

    return dict(div_counts=dc, div_survival=ds, biz_counts=bc,
                emp_dist=ed, wage_share=ws, subdiv_to_div=subdiv_to_div)


def build_options(dfs: dict, level: int) -> list:
    if level == 1:
        dc = dfs["div_counts"]
        return [] if dc.empty else [(d, d) for d in sorted(dc["division"].unique())]
    if level == 2:
        ws = dfs["wage_share"]
        if ws.empty:
            return []
        rows = ws[["subdivision_code","subdivision_name","division"]].drop_duplicates().sort_values("subdivision_code")
        return [(r["subdivision_code"],
                 f"{r['subdivision_code']} – {r['subdivision_name']}  ({r['division'][:22]}…)")
                for _, r in rows.iterrows()]
    bc = dfs["biz_counts"]
    if bc.empty:
        return []
    latest = bc[bc["year"] == bc["year"].max()]
    grp = (latest.groupby("anzsic_group_code")
           .agg(total=("total_businesses","sum"), n=("anzsic_class_code","count"))
           .reset_index().sort_values("anzsic_group_code"))
    first_name = bc.groupby("anzsic_group_code")["anzsic_class_name"].first().to_dict()
    return [(r["anzsic_group_code"],
             f"{r['anzsic_group_code']} – {first_name.get(r['anzsic_group_code'],'')[:40]}  "
             f"({int(r['total']):,} firms)")
            for _, r in grp.iterrows()]


def filter_dfs(dfs: dict, level: int, codes: list) -> dict:
    empty = {k: pd.DataFrame()
             for k in ["div_counts","div_survival","biz_counts","emp_dist","wage_share"]}
    if not codes:
        return empty
    dc, ds, bc, ed, ws = (dfs[k].copy() for k in
                          ["div_counts","div_survival","biz_counts","emp_dist","wage_share"])
    s2d = dfs["subdiv_to_div"]
    if level == 1:
        dc = dc[dc["division"].isin(codes)]
        ds = ds[ds["division"].isin(codes)]
        ws = ws[ws["division"].isin(codes)]
        bc = bc[bc["division"].isin(codes)] if "division" in bc.columns else pd.DataFrame()
        ed = ed[ed["division"].isin(codes)] if "division" in ed.columns else pd.DataFrame()
    elif level == 2:
        pdivs = {s2d[c] for c in codes if c in s2d}
        dc = dc[dc["division"].isin(pdivs)]
        ds = ds[ds["division"].isin(pdivs)]
        ws = ws[ws["subdivision_code"].isin(codes)]
        bc = bc[bc["subdivision_code"].isin(codes)] if "subdivision_code" in bc.columns else pd.DataFrame()
        ed = ed[ed["subdivision_code"].isin(codes)] if "subdivision_code" in ed.columns else pd.DataFrame()
    else:
        psubs = {c[:2] for c in codes}
        pdivs = {s2d[s] for s in psubs if s in s2d}
        dc = dc[dc["division"].isin(pdivs)]
        ds = ds[ds["division"].isin(pdivs)]
        ws = ws[ws["subdivision_code"].isin(psubs)]
        bc = bc[bc["anzsic_group_code"].isin(codes)]
        ed = ed[ed["anzsic_group_code"].isin(codes)]
    return dict(div_counts=dc, div_survival=ds, biz_counts=bc, emp_dist=ed, wage_share=ws)


