# ═══════════════════════════════════════════════════════════════════════════════
# TAB 2 — Firm Size Structure (ANZSIC class level, 2024 & 2025)
# Source: abs_employment_dist.csv
# ═══════════════════════════════════════════════════════════════════════════════

with tab2:
    st.subheader("Firm Size Structure by ANZSIC Class (ABS 8165.0)")
    st.markdown(
        "Breakdown of businesses by employment size band: "
        "**Non-employing** (sole traders), **1–4**, **5–19**, **20–199**, **200+** employees. "
        "Data is at the 4-digit ANZSIC *class* level (the most granular available in 8165.0), "
        "covering June 2024 and June 2025."
    )

    if df_emp_dist.empty:
        st.info("No employment distribution data found. Run the fetch script to populate this.")
    else:
        df_ed = df_emp_dist.copy()
        latest_yr = int(df_ed["year"].max())
        df_ed_latest = df_ed[df_ed["year"] == latest_yr].copy()

        # Search / filter by class name
        search = st.text_input("🔍 Filter by class name (e.g. 'retail', 'construc', 'medical')",
                               placeholder="Leave blank to show top 30 by firm count")
        if search.strip():
            df_ed_latest = df_ed_latest[
                df_ed_latest["anzsic_class_name"].str.contains(search.strip(), case=False, na=False)
            ]
        else:
            df_ed_latest = df_ed_latest.nlargest(30, "total_businesses")

        if df_ed_latest.empty:
            st.info("No classes match your search.")
        else:
            size_cols   = ["non_employing", "emp_1_4", "emp_5_19", "emp_20_199", "emp_200plus"]
            size_labels = {
                "non_employing": "Non-employing",
                "emp_1_4":       "1–4 employees",
                "emp_5_19":      "5–19 employees",
                "emp_20_199":    "20–199 employees",
                "emp_200plus":   "200+ employees",
            }

            df_melt = df_ed_latest.melt(
                id_vars=["anzsic_class_code", "anzsic_class_name", "year"],
                value_vars=size_cols,
                var_name="size_band", value_name="count",
            )
            df_melt["size_label"] = df_melt["size_band"].map(size_labels)
            # Preserve size order
            size_order = list(size_labels.values())
            df_melt["size_label"] = pd.Categorical(df_melt["size_label"],
                                                   categories=size_order, ordered=True)
            df_melt = df_melt.sort_values(["anzsic_class_name", "size_label"])

            view = st.radio("View", ["Count", "% share"], horizontal=True)

            if view == "Count":
                fig = px.bar(
                    df_melt,
                    x="anzsic_class_name", y="count", color="size_label",
                    category_orders={"size_label": size_order},
                    title=f"Employment Size Breakdown — {len(df_ed_latest)} classes (June {latest_yr})",
                    labels={"count": "Businesses", "anzsic_class_name": "",
                            "size_label": "Size band"},
                    color_discrete_sequence=px.colors.sequential.Blues[1:],
                )
                fig.update_layout(yaxis_tickformat=",")
            else:
                # Compute % within each class
                tot = df_ed_latest.set_index("anzsic_class_code")[size_cols].sum(axis=1)
                df_pct = df_ed_latest.copy()
                for col in size_cols:
                    df_pct[col] = (df_pct[col] / tot.reindex(df_pct["anzsic_class_code"]).values * 100).round(1)
                df_pct_melt = df_pct.melt(
                    id_vars=["anzsic_class_code", "anzsic_class_name"],
                    value_vars=size_cols, var_name="size_band", value_name="pct",
                )
                df_pct_melt["size_label"] = df_pct_melt["size_band"].map(size_labels)
                df_pct_melt["size_label"] = pd.Categorical(
                    df_pct_melt["size_label"], categories=size_order, ordered=True)
                df_pct_melt = df_pct_melt.sort_values(["anzsic_class_name", "size_label"])
                fig = px.bar(
                    df_pct_melt,
                    x="anzsic_class_name", y="pct", color="size_label",
                    category_orders={"size_label": size_order},
                    title=f"Employment Size Share — {len(df_ed_latest)} classes (June {latest_yr})",
                    labels={"pct": "% of businesses", "anzsic_class_name": "",
                            "size_label": "Size band"},
                    color_discrete_sequence=px.colors.sequential.Blues[1:],
                )
                fig.update_layout(yaxis_range=[0, 100])

            fig.update_xaxes(tickangle=45)
            fig.update_layout(height=500, legend_title="Size band")
            st.plotly_chart(fig, use_container_width=True)

            with st.expander("📋 Show data table"):
                show_cols = ["anzsic_class_code", "anzsic_class_name", "year",
                             "non_employing", "emp_1_4", "emp_5_19", "emp_20_199",
                             "emp_200plus", "total_businesses"]
                st.dataframe(df_ed_latest[show_cols].sort_values("total_businesses", ascending=False),
                             use_container_width=True)

    with st.expander("ℹ️ How to interpret this"):
        st.markdown("""
Most Australian industries are dominated by **non-employing** businesses (sole traders
and self-employed) and micro-firms (1–4 employees).  This is typical and expected.

A class with an unusually **high share of large firms** may indicate structural
concentration — though you'd need revenue/turnover data to confirm market power.

A trend towards **fewer micro firms** and **more medium/large** over time can be an
early signal of consolidation pressure (use the 2024 vs 2025 toggle to check).

Regulatory compliance costs are generally proportionally higher for smaller firms
(fixed costs spread over less revenue), so size structure affects regulatory burden estimates.
        """)

